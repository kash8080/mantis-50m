"""The tokenizer's training corpus: a ~2 GB sample of the stable mix in proportion to its weights (D-018).

Streams the first rows of each source's parquet files from the Hub, one row group at a time, and stops
at that source's byte budget. Most first files are 1-2 GB but a source needs only 40-900 MB, so whole
files are never downloaded. The synthetic arithmetic is generated at its share. Writes to data/tokenizer/:

    corpus/<source>.jsonl   one {"text": ...} per document. Gitignored
    manifest.json           files, rows and bytes per source, with the HF commit. Committed
    README.md               where the data is from, written from the manifest. Committed
"""

import json
import random
import time
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import BinaryIO

from slm50m.arith.generator import generate_document
from slm50m.config import STABLE_MIX
from slm50m.dataprep.sources import SOURCES, Part, iter_texts, list_parquet_files


def open_remote(part: Part, filename: str) -> BinaryIO:
    """A seekable handle on a Hub file. pyarrow then fetches only the row groups it reads."""
    from huggingface_hub import HfFileSystem

    return HfFileSystem().open(f"datasets/{part.repo}@{part.revision}/{filename}", "rb")


def take_part(part: Part, budget: float, files: list[str], opener: Callable[[Part, str], BinaryIO],
              files_used: list[dict]) -> Iterator[str]:
    """Documents from the first files of one part until `budget` bytes. Appends one entry per file read."""
    seen = 0
    for filename in files:
        entry = {"file": filename, "rows": 0, "bytes": 0}
        files_used.append(entry)
        with opener(part, filename) as fh:
            for text in iter_texts(fh, part):
                n = len(text.encode())
                entry["rows"] += 1
                entry["bytes"] += n
                seen += n
                yield text
                if seen >= budget:
                    return


def build_corpus(out_dir: str | Path, total_bytes: float, mix: dict[str, float] = STABLE_MIX, seed: int = 0,
                 opener: Callable[[Part, str], BinaryIO] = open_remote) -> dict:
    out_dir = Path(out_dir)
    (out_dir / "corpus").mkdir(parents=True, exist_ok=True)
    manifest = {"total_bytes": total_bytes, "seed": seed, "mix": mix, "built": time.strftime("%d %b %Y"),
                "sources": {}}
    for name, weight in mix.items():
        budget = weight * total_bytes
        t0 = time.time()
        entry = {"weight": weight, "budget_bytes": int(budget), "licence": SOURCES[name].licence, "parts": []}
        with open(out_dir / "corpus" / f"{name}.jsonl", "w") as f:
            if name == "arith":
                rng, seen, docs = random.Random(seed), 0, 0
                while seen < budget:
                    doc = generate_document(rng)
                    seen += len(doc.encode())
                    docs += 1
                    f.write(json.dumps({"text": doc}) + "\n")
                entry["parts"].append({"repo": None, "generated": {"rows": docs, "bytes": seen}})
            else:
                # word problems has two parts: split its budget by half (sizes are only known after prep)
                parts = SOURCES[name].parts
                for part in parts:
                    files_used: list[dict] = []
                    texts = take_part(part, budget / len(parts), list_parquet_files(part), opener, files_used)
                    f.writelines(json.dumps({"text": text}) + "\n" for text in texts)
                    entry["parts"].append({"repo": part.repo, "revision": part.revision, "prefix": part.prefix,
                                           "files": files_used})
        entry["bytes"] = sum(p["generated"]["bytes"] if p["repo"] is None else sum(x["bytes"] for x in p["files"])
                             for p in entry["parts"])
        manifest["sources"][name] = entry
        print(f"tokenizer corpus: {name:15s} {entry['bytes'] / 1e6:7.1f} MB in {time.time() - t0:5.0f}s", flush=True)
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    (out_dir / "README.md").write_text(readme(manifest))
    return manifest


def iter_corpus_texts(corpus_dir: str | Path) -> Iterator[str]:
    """Every document of a built corpus, source by source. BPE training only counts words, so order doesn't matter."""
    for path in sorted((Path(corpus_dir) / "corpus").glob("*.jsonl")):
        with open(path) as f:
            for line in f:
                yield json.loads(line)["text"]


def readme(manifest: dict) -> str:
    rows = []
    for name, s in manifest["sources"].items():
        for p in s["parts"]:
            if p["repo"] is None:
                where, commit, files = "generated by `src/slm50m/arith/`", "n/a", "n/a"
                docs, n_bytes = p["generated"]["rows"], p["generated"]["bytes"]
            else:
                where = f"[`{p['repo']}`](https://huggingface.co/datasets/{p['repo']}) `{p['prefix'] or '/'}`"
                commit, files = f"`{p['revision'][:10]}`", str(len(p["files"]))
                docs, n_bytes = sum(x["rows"] for x in p["files"]), sum(x["bytes"] for x in p["files"])
            rows.append(f"| {name} | {s['weight']:.0%} | {where} | {commit} | {s['licence']} | {files} | {docs:,} "
                        f"| {n_bytes / 1e6:,.1f} |")
    total = sum(s["bytes"] for s in manifest["sources"].values())
    return f"""# Tokenizer training corpus

The text the 16,384-token BPE tokenizer is trained on (D-018). It is a sample of the stable training mix
(D-023), with each source in proportion to its mix weight. Built {manifest['built']}: {total / 1e9:.2f} GB of
text in total, arithmetic seed {manifest['seed']}.

## What's here

| Path | What | In git |
|---|---|---|
| `corpus/<source>.jsonl` | one `{{"text": ...}}` per document | no (too big) |
| `manifest.json` | every file read, with rows and bytes, and the HF commit of each repo | yes |
| `README.md` | this file, written by the build from the manifest | yes |

The trained tokenizer is not here. It goes to `outputs/tokenizer/`.

## Sources

Each source takes the first rows of its first parquet files (sorted by name) until its byte budget is
met. The files are already shuffled by their publishers, so the first rows are a fair sample.

| Source | Mix | Where | Commit | Licence | Files read | Documents | MB of text |
|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

Notes:
- Word problems is two parts with half the budget each. From OpenMathInstruct-2 only rows whose
  `problem_source` is `gsm8k` or `augmented_gsm8k` are kept, written as "Question: ... Answer: ..."
- Licences and why each source was picked: D-022 in `docs/decisions.md`. Mix weights: D-023

## Rebuild

    uv run slm-build-tokenizer-corpus --gb 2

Same commits and same seed give the same corpus.
"""
